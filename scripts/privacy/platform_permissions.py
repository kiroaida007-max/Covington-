#!/usr/bin/env python3
"""Generates the privacy map's table of platform methods and the permissions they require.

Source: the Android SDK's own annotations (platform-35's data/annotations.zip, extracted by
scripts/setup-toolchain.sh --full or by hand), which carry androidx.annotation.RequiresPermission for
every public API that checks a permission, with anyOf/allOf, the API levels a requirement applies to
("apis") and whether it applies only to part of the result ("conditional").

Output (committed): modules/app-recovery/src/main/resources/dev/apkproject/app/platform-permissions.tsv
  class <TAB> method <TAB> parameter types <TAB> mode (anyOf|allOf) <TAB> permissions <TAB> apis <TAB> conditional
Permissions are written without the android.permission. prefix when they have it.

Usage: python3 -I scripts/privacy/platform_permissions.py [annotations-dir] [output]
"""
import glob
import html
import os
import re
import sys

ITEM = re.compile(r'<item name="([^"]+)">(.*?)</item>', re.S)
VAL = re.compile(r'<val name="([^"]+)" val="([^"]*)"\s*/>')
# "android.location.LocationManager android.location.Location getLastKnownLocation(java.lang.String)"
METHOD = re.compile(r'^(\S+) (?:\S+ )?([A-Za-z_$][\w$]*)\((.*)\)$')


def strip_generics(t):
    depth, out = 0, []
    for ch in t:
        if ch == '<':
            depth += 1
        elif ch == '>':
            depth -= 1
        elif depth == 0:
            out.append(ch)
    return ''.join(out).strip()


def parse(root):
    rows = {}
    for path in sorted(glob.glob(os.path.join(root, '**', 'annotations.xml'), recursive=True)):
        with open(path, encoding='utf-8') as f:
            text = f.read()
        for m in ITEM.finditer(text):
            name, body = html.unescape(m.group(1)), m.group(2)
            if 'androidx.annotation.RequiresPermission' not in body:
                continue
            ann = body[body.index('androidx.annotation.RequiresPermission'):]
            ann = ann[:ann.index('</annotation>')] if '</annotation>' in ann else ann
            vals = {k: html.unescape(v) for k, v in VAL.findall(ann)}
            mm = METHOD.match(name)
            if not mm:
                continue  # fields and classes: not calls
            cls, method, params = mm.group(1), mm.group(2), mm.group(3)
            if cls.split('.')[-1] == method:
                method = '<init>'
            params = ','.join(strip_generics(p).replace(' ', '') for p in split_params(params))
            if 'allOf' in vals:
                mode, perms = 'allOf', vals['allOf']
            elif 'anyOf' in vals:
                mode, perms = 'anyOf', vals['anyOf']
            elif 'value' in vals:
                mode, perms = 'anyOf', vals['value']
            else:
                continue
            names = [p.strip().strip('"') for p in perms.strip('{}').split(',') if p.strip().strip('"')]
            names = [p[len('android.permission.'):] if p.startswith('android.permission.') else p for p in names]
            if not names:
                continue
            apis = vals.get('apis', '').strip('"')
            conditional = 'true' if vals.get('conditional') == 'true' else ''
            rows[(cls, method, params)] = (mode, ','.join(sorted(set(names))), apis, conditional)
    return rows


def split_params(s):
    out, depth, cur = [], 0, []
    for ch in s:
        if ch == '<':
            depth += 1
        elif ch == '>':
            depth -= 1
        if ch == ',' and depth == 0:
            out.append(''.join(cur))
            cur = []
        else:
            cur.append(ch)
    if ''.join(cur).strip():
        out.append(''.join(cur))
    return [p.strip() for p in out]


def main():
    here = os.path.dirname(os.path.abspath(__file__))
    repo = os.path.dirname(os.path.dirname(here))
    root = sys.argv[1] if len(sys.argv) > 1 else os.path.join(repo, '.tools', 'dl', 'sdk', 'ann')
    out = sys.argv[2] if len(sys.argv) > 2 else os.path.join(repo, 'modules', 'app-recovery', 'src', 'main', 'resources', 'dev', 'apkproject', 'app', 'platform-permissions.tsv')
    rows = parse(root)
    if not rows:
        sys.exit(f'no RequiresPermission items under {root}')
    with open(out, 'w', encoding='utf-8', newline='\n') as f:
        f.write('# Platform methods and the permissions they require, from the Android SDK 35 annotations\n')
        f.write('# (platform-35 data/annotations.zip, androidx.annotation.RequiresPermission). Generated by\n')
        f.write('# scripts/privacy/platform_permissions.py; do not edit by hand.\n')
        f.write('# class\tmethod\tparameters\tmode\tpermissions\tapis\tconditional\n')
        for (cls, method, params), (mode, perms, apis, cond) in sorted(rows.items()):
            f.write(f'{cls}\t{method}\t{params}\t{mode}\t{perms}\t{apis}\t{cond}\n')
    print(f'{len(rows)} methods -> {out}')


if __name__ == '__main__':
    main()
